/**
 * Bundle the CLI (and everything it imports) into dist/cli.mjs.
 *
 * The workspace packages import each other by package name, which only resolves
 * inside the monorepo. Bundling makes the published package self-contained: one
 * file, Node built-ins only, no runtime dependencies to install.
 */
import fs from 'node:fs';
import path from 'node:path';
import * as esbuild from 'esbuild';

const root = process.cwd();
const outfile = path.join(root, 'dist', 'cli.mjs');

const result = await esbuild.build({
  entryPoints: [path.join(root, 'packages/runtime/src/cli.ts')],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  sourcemap: false,
  // Native optional deps of `ws` are not needed for our client/server use.
  external: ['bufferutil', 'utf-8-validate'],
  // `ws` is CommonJS and calls require() internally; an ESM bundle needs a
  // real require to hand to it.
  banner: {
    js: [
      '// Bundled CLI. Generated by scripts/build-cli.mjs — do not edit.',
      "import { createRequire as __createRequire } from 'node:module';",
      'const require = __createRequire(import.meta.url);',
    ].join('\n'),
  },
  logLevel: 'warning',
});

const size = (fs.statSync(outfile).size / 1024).toFixed(0);
console.log(`  bundled dist/cli.mjs (${size} KiB)`);
if (result.warnings.length) console.log(`  ${result.warnings.length} warning(s)`);
